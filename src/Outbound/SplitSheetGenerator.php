declare(strict_types=1);

namespace MDS\Licensing\Outbound;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Generates print-ready Split Sheet Agreements with signature blocks.
 *
 * @since 0.1.0
 */
final class SplitSheetGenerator {

	/**
	 * Builds a printable Split Sheet Agreement HTML document for a Release.
	 *
	 * @param int $post_id Release post ID.
	 * @return string
	 */
	public static function build_html( int $post_id ): string {
		$title  = get_the_title( $post_id );
		$upc    = (string) get_post_meta( $post_id, 'barcode', true );
		$tracks = class_exists( '\MDS\Metadata\Core\CatalogMeta' )
			? \MDS\Metadata\Core\CatalogMeta::get_tracklist( $post_id )
			: array();

		if ( empty( $tracks ) ) {
			$tracks = array(
				array(
					'number' => 1,
					'title'  => $title,
					'isrc'   => '',
					'iswc'   => '',
					'splits' => array(),
				),
			);
		}

		$h  = '<!doctype html><html lang="en"><head><meta charset="utf-8"><title>Split Sheet Agreement — ' . esc_html( $title ) . '</title>';
		$h .= '<style>body{font-family:system-ui,-apple-system,sans-serif;max-width:860px;margin:24px auto;padding:0 16px;color:#1d2327;line-height:1.5}table{width:100%;border-collapse:collapse;margin:12px 0 20px}th,td{border:1px solid #8c8f94;padding:8px;text-align:left;font-size:13px}th{background:#f0f0f1}.sig{height:38px}.note{font-size:12px;color:#50575e;border-top:1px solid #dcdcde;padding-top:10px;margin-top:24px}@media print{body{margin:0}}</style></head><body>';
		$h .= '<h1>Songwriting &amp; Master Split Sheet Agreement</h1>';
		$h .= '<p><strong>Release:</strong> ' . esc_html( $title ) . ( '' !== $upc ? ' &nbsp;|&nbsp; <strong>UPC:</strong> ' . esc_html( $upc ) : '' ) . ' &nbsp;|&nbsp; <strong>Date:</strong> ' . esc_html( gmdate( 'Y-m-d' ) ) . '</p>';
		$h .= '<p>The undersigned parties hereby confirm and agree to the ownership percentages set forth below for the musical compositions and/or sound recordings listed herein.</p>';

		foreach ( $tracks as $idx => $t ) {
			$h     .= '<h3>Track ' . esc_html( (string) ( $t['number'] ?? ( $idx + 1 ) ) ) . ': ' . esc_html( (string) ( $t['title'] ?? '' ) ) . '</h3>';
			$h     .= '<p style="font-size:12px;margin-top:-8px;color:#50575e">ISRC: ' . esc_html( (string) ( $t['isrc'] ?? 'TBD' ) ) . ' &nbsp;|&nbsp; ISWC: ' . esc_html( (string) ( $t['iswc'] ?? 'TBD' ) ) . '</p>';
			$h     .= '<table><thead><tr><th>Name</th><th>Role / Type</th><th>PRO</th><th>IPI #</th><th>Share %</th><th>Signature &amp; Date</th></tr></thead><tbody>';
			$splits = is_array( $t['splits'] ?? null ) ? $t['splits'] : array();
			if ( empty( $splits ) ) {
				for ( $i = 0; $i < 3; $i++ ) {
					$h .= '<tr><td></td><td></td><td></td><td></td><td>%</td><td class="sig"></td></tr>';
				}
			} else {
				foreach ( $splits as $sp ) {
					$h .= '<tr><td>' . esc_html( (string) ( $sp['name'] ?? '' ) ) . '</td><td>' . esc_html( (string) ( $sp['role'] ?? $sp['type'] ?? 'Writer' ) ) . '</td><td>' . esc_html( (string) ( $sp['pro'] ?? '' ) ) . '</td><td>' . esc_html( (string) ( $sp['ipi'] ?? '' ) ) . '</td><td>' . esc_html( (string) ( $sp['share_pct'] ?? 0 ) ) . '%</td><td class="sig"></td></tr>';
				}
			}
			$h .= '</tbody></table>';
		}

		$h .= '<p class="note"><em>Administrative Split Sheet Template generated by MDS Licensing (Musty Dungeon Studios). Consult an entertainment attorney for custom publishing or master-use agreements.</em></p>';
		$h .= '</body></html>';
		return $h;
	}
}
